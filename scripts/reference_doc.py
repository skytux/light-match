"""Write docs/reference-space.md from custom_components/light_match/reference.py."""

from __future__ import annotations

from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from custom_components.light_match import reference  # noqa: E402

HEAD = """# The reference space lm-ref-1

Profiles in the shared database are calibrated against one common target, so
a profile made in one home works in another. This file is generated by
`scripts/reference_doc.py` from `custom_components/light_match/reference.py`.

- **Colour cells:** the fully saturated sRGB colour of the anchor hue (D65
  white point) as CIE 1931 xy, pulled into Philips Hue gamut C where it lies
  just outside it (only blue does).
- **White cells:** the Planckian locus at the cell's colour temperature.
- **Brightness:** the cell's percentage is perceived lightness (CIE L*), so
  the relative light output is `luminance(L* = percentage)` of the lamp's own
  maximum. There are no absolute lumens: a brighter lamp is not dimmed to
  match a weaker one.

Every target lies inside Hue gamut C. A Hue colour lamp with gamut C (White
and Color Ambiance; the model ids are in `profiles/signify/hue-gamut-c.json`)
sent `xy_color` and the same Home Assistant brightness shows lm-ref-1 closely
enough to serve as the reference when calibrating by eye. Light Match sends it
that command when you pick such a lamp as the reference in the panel.

Profiles calibrated against any other lamp get the target `house`. They work
in that home (that is the personal layer: "match my reference lamp"), but the
database only takes `lm-ref-1` profiles.

| Cell | x | y | Relative output |
|---|---|---|---|
"""


def text() -> str:
    """The document."""
    rows = [
        f"| `{t['key']}` | {t['xy'][0]:.4f} | {t['xy'][1]:.4f} | {t['relative_output']:.4g} |"
        for t in reference.reference_table()
    ]
    return HEAD + "\n".join(rows) + "\n"


if __name__ == "__main__":
    out = ROOT / "docs" / "reference-space.md"
    if sys.argv[1:] == ["check"]:
        sys.exit(0 if out.read_text(encoding="utf-8") == text() else 1)
    out.write_text(text(), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}")
